#include <iostream>
#include <string>
#include <cctype>
#include <clocale>

using namespace std;

int main() {
    setlocale(LC_ALL, "Russian");

    char code;
    int score, attendance, work;

    cout << "Введите код формы контроля (E — экзамен, T — тест, P — проект): ";
    cin >> code;

    cout << "Введите основной балл 0..100: ";
    cin >> score;

    cout << "Введите посещаемость 0..100: ";
    cin >> attendance;

    cout << "Введите признак выполнения обязательной работы (0/1): ";
    cin >> work;

    if (score < 0 || score > 100 ||
        attendance < 0 || attendance > 100 ||
        (work != 0 && work != 1)) {
        cout << "Ошибка: данные вне допустимых диапазонов.\n";
        return 0;
    }

    bool ok = false;
    string reason;

    switch (toupper(static_cast<unsigned char>(code))) {
    case 'E':
        if (score < 50)
            reason = "основной балл ниже 50";
        else if (attendance < 75)
            reason = "посещаемость ниже 75";
        else if (work != 1)
            reason = "не выполнена обязательная работа";
        else {
            ok = true;
            reason = "все условия выполнены";
        }
        break;

    case 'T':
        if (score < 60)
            reason = "основной балл ниже 60";
        else if (attendance < 60)
            reason = "посещаемость ниже 60";
        else if (work != 1)
            reason = "не выполнена обязательная работа";
        else {
            ok = true;
            reason = "все условия выполнены";
        }
        break;

    case 'P':
        if (score < 70)
            reason = "основной балл ниже 70";
        else if (work != 1)
            reason = "не выполнена обязательная работа";
        else {
            ok = true;
            reason = "все условия выполнены (посещаемость для проекта не ограничивает)";
        }
        break;

    default:
        cout << "Ошибка: неизвестный код формы контроля.\n";
        return 0;
    }

    cout << "Итог: " << (ok ? "допуск/зачёт есть" : "допуска/зачёта нет") << ". ";
    if (ok)
        cout << reason << ".\n";
    else
        cout << "Причина: " << reason << ".\n";

    return 0;
}
